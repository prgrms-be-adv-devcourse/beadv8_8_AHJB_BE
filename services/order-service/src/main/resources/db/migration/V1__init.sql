CREATE TABLE order_member (
                              id          bigint       NOT NULL,
                              created_at  timestamp(6) NOT NULL,
                              updated_at  timestamp(6) NOT NULL,
                              uuid        uuid         NOT NULL,
                              nickname    varchar(255) NOT NULL,
                              CONSTRAINT pk_order_member PRIMARY KEY (id),
                              CONSTRAINT uk_order_member_uuid UNIQUE (uuid)
);

CREATE TABLE cart_item (
                           id                       bigint GENERATED BY DEFAULT AS IDENTITY,
                           created_at               timestamp(6) NOT NULL,
                           updated_at               timestamp(6) NOT NULL,
                           winner_id                bigint       NOT NULL,
                           seller_id                bigint       NOT NULL,
                           auction_id               bigint       NOT NULL,
                           product_id               bigint       NOT NULL,
                           winning_price            bigint,
                           delivery_fee             bigint,
                           win_at                   timestamp(6) NOT NULL,
                           payment_due_at           timestamp(6) NOT NULL,
                           payment_default_alarmed  boolean      NOT NULL DEFAULT false,
                           CONSTRAINT pk_cart_item PRIMARY KEY (id),
                           CONSTRAINT uk_cart_item_auction_id UNIQUE (auction_id),
                           CONSTRAINT fk_cart_item_winner FOREIGN KEY (winner_id) REFERENCES order_member (id),
                           CONSTRAINT fk_cart_item_seller FOREIGN KEY (seller_id) REFERENCES order_member (id)
);

CREATE TABLE order_group (
                             id           bigint GENERATED BY DEFAULT AS IDENTITY,
                             created_at   timestamp(6) NOT NULL,
                             updated_at   timestamp(6) NOT NULL,
                             total_price  bigint       NOT NULL,
                             winner_id    bigint,
                             life_time    timestamp(6),
                             CONSTRAINT pk_order_group PRIMARY KEY (id),
                             CONSTRAINT fk_order_group_winner FOREIGN KEY (winner_id) REFERENCES order_member (id)
);

CREATE TABLE orders (
                        id                    bigint GENERATED BY DEFAULT AS IDENTITY,
                        created_at            timestamp(6) NOT NULL,
                        updated_at            timestamp(6) NOT NULL,
                        group_id              bigint       NOT NULL,
                        winner_id             bigint       NOT NULL,
                        seller_id             bigint       NOT NULL,
                        auction_id            bigint       NOT NULL,
                        product_id            bigint       NOT NULL,
                        winning_price         bigint       NOT NULL,
                        delivery_fee          bigint       NOT NULL,
                        paid_at               timestamp(6),
                        confirm_expired_at    timestamp(6),
                        state                 varchar(30)  NOT NULL,
                        auto_confirm_alarmed  boolean      NOT NULL DEFAULT false,
                        CONSTRAINT pk_orders PRIMARY KEY (id),
                        CONSTRAINT fk_orders_group FOREIGN KEY (group_id) REFERENCES order_group (id),
                        CONSTRAINT fk_orders_winner FOREIGN KEY (winner_id) REFERENCES order_member (id),
                        CONSTRAINT fk_orders_seller FOREIGN KEY (seller_id) REFERENCES order_member (id),
                        CONSTRAINT ck_orders_state CHECK (state IN ('WAITING', 'PAID', 'FAILED', 'SHIPPING', 'SHIPPED', 'CONFIRMED', 'REFUND_REQUESTED', 'REFUNDED', 'DELIVERY_ERROR'))
);
