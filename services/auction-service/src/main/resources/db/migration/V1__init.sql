CREATE TABLE auction (
                         id                      bigint GENERATED BY DEFAULT AS IDENTITY,
                         auction_type            varchar(20)  NOT NULL,
                         created_at              timestamp(6) NOT NULL,
                         updated_at              timestamp(6) NOT NULL,
                         product_id              bigint       NOT NULL,
                         seller_id               bigint       NOT NULL,
                         start_price             bigint       NOT NULL,
                         shipping_fee            bigint,
                         category                varchar(255),
                         status                  varchar(255) NOT NULL,
                         failure_reason          varchar(255),
                         winner_id               bigint,
                         winning_price           bigint,
                         win_at                  timestamp(6),
                         start_at                timestamp(6) NOT NULL,
                         end_at                  timestamp(6) NOT NULL,
                         version                 bigint,
                         instant_win_price       bigint,
                         highest_bid_price       bigint,
                         highest_bidder_id       bigint,
                         bid_count               integer,
                         ending_soon_notified_at timestamp(6),
                         floor_price             bigint,
                         drop_rate_percent       integer,
                         drop_interval_sec       integer,
                         CONSTRAINT pk_auction PRIMARY KEY (id),
                         CONSTRAINT ck_auction_type CHECK (auction_type IN ('ENGLISH', 'DUTCH')),
                         CONSTRAINT ck_auction_status CHECK (status IN ('IN_PROGRESS', 'WON', 'PAID', 'COMPLETED', 'FAILED')),
                         CONSTRAINT ck_auction_failure_reason CHECK (failure_reason IN ('NO_BID', 'UNPAID', 'REFUNDED'))
);

CREATE INDEX idx_auction_status_end_at ON auction (status, end_at);
CREATE INDEX idx_auction_status_category_end_at ON auction (status, category, end_at);

CREATE TABLE bid (
                     id         bigint GENERATED BY DEFAULT AS IDENTITY,
                     auction_id bigint       NOT NULL,
                     bidder_id  bigint       NOT NULL,
                     bid_price  bigint       NOT NULL,
                     bid_at     timestamp(6) NOT NULL,
                     CONSTRAINT pk_bid PRIMARY KEY (id)
);

CREATE INDEX idx_bid_bidder_auction ON bid (bidder_id, auction_id);

CREATE TABLE auction_member (
                                id         bigint       NOT NULL,
                                created_at timestamp(6) NOT NULL,
                                updated_at timestamp(6) NOT NULL,
                                nickname   varchar(255) NOT NULL,
                                CONSTRAINT pk_auction_member PRIMARY KEY (id)
);