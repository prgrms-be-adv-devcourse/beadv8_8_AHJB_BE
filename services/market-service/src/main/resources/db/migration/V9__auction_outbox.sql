-- 경매 외부 이벤트 아웃박스 (#548). 팀 공통 아웃박스(order_outbox, delivery_outbox)와 같은 구조.
-- 경매 시작·낙찰·유찰 이벤트를 상태 변경과 같은 트랜잭션에서 저장하고, 스케줄러가 Kafka로 보낸 뒤 published_at을 기록한다.
-- 스케줄러가 Kafka를 직접 기다리지 않게 해서 같은 분 종료 지연·브로커 중단 시 스케줄러 정지를 없애고, 커밋 후 유실을 막는다.
CREATE TABLE auction_outbox (
                            id            bigint GENERATED BY DEFAULT AS IDENTITY,
                            created_at    timestamp(6) NOT NULL,
                            updated_at    timestamp(6) NOT NULL,
                            topic         varchar(100) NOT NULL,
                            message_key   varchar(100) NOT NULL,
                            payload       text         NOT NULL,
                            published_at  timestamp(6),
                            CONSTRAINT pk_auction_outbox PRIMARY KEY (id)
);
CREATE INDEX idx_auction_outbox_published_at ON auction_outbox (published_at, id);
