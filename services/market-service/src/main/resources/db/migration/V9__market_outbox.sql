-- market 외부 이벤트 아웃박스 (#548). 팀 공통 아웃박스(order_outbox, delivery_outbox)와 같은 구조.
-- market은 상품·경매·리뷰가 한 컨텍스트라(11/17 통합 결정) 테이블도 하나다. 팀 규칙: 컨텍스트마다 아웃박스 하나.
-- 경매(시작·낙찰·유찰)·상품(등록·변경·찜) 이벤트를 상태 변경과 같은 트랜잭션에서 저장하고,
-- 스케줄러가 Kafka로 보낸 뒤 published_at을 기록한다.
-- 스케줄러가 Kafka를 직접 기다리지 않게 해서 브로커 중단 시 경매 종료·열기 정지를 없애고, 커밋 후 유실을 막는다.
CREATE TABLE market_outbox (
                            id            bigint GENERATED BY DEFAULT AS IDENTITY,
                            created_at    timestamp(6) NOT NULL,
                            updated_at    timestamp(6) NOT NULL,
                            topic         varchar(100) NOT NULL,
                            message_key   varchar(100) NOT NULL,
                            payload       text         NOT NULL,
                            published_at  timestamp(6),
                            CONSTRAINT pk_market_outbox PRIMARY KEY (id)
);
CREATE INDEX idx_market_outbox_published_at ON market_outbox (published_at, id);
