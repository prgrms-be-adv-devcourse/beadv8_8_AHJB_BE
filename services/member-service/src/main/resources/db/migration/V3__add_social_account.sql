-- 소셜 로그인(카카오) 회원 지원
-- 소셜 회원은 비밀번호가 없으므로 password 를 nullable 로 바꾼다.
ALTER TABLE member ALTER COLUMN password DROP NOT NULL;

-- 외부 제공자 계정과 회원의 연결
-- (provider, provider_user_id) 유니크: 같은 카카오 계정으로 두 번 가입되는 것을 DB 에서 막는다.
-- (member_id, provider) 유니크: 한 회원에 같은 제공자 계정이 여러 개 연결되지 않게 한다.
CREATE TABLE social_account (
                                id                bigint GENERATED BY DEFAULT AS IDENTITY,
                                created_at        timestamp(6) NOT NULL,
                                updated_at        timestamp(6) NOT NULL,
                                member_id         bigint       NOT NULL,
                                provider          varchar(20)  NOT NULL,
                                provider_user_id  varchar(100) NOT NULL,
                                CONSTRAINT pk_social_account PRIMARY KEY (id),
                                CONSTRAINT uk_social_account_provider_user UNIQUE (provider, provider_user_id),
                                CONSTRAINT uk_social_account_member_provider UNIQUE (member_id, provider),
                                CONSTRAINT ck_social_account_provider CHECK (provider IN ('KAKAO'))
);
