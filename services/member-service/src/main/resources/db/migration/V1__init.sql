-- member
CREATE TABLE member (
                        id                bigint GENERATED BY DEFAULT AS IDENTITY,
                        created_at        timestamp(6) NOT NULL,
                        updated_at        timestamp(6) NOT NULL,
                        uuid              uuid         NOT NULL,
                        email             varchar(255) NOT NULL,
                        password          varchar(100) NOT NULL,
                        nickname          varchar(50)  NOT NULL,
                        username          varchar(50)  NOT NULL,
                        phone             varchar(20)  NOT NULL,
                        birth_date        date,
                        locked            boolean      NOT NULL,
                        locked_until      timestamp(6),
                        login_fail_count  integer      NOT NULL,
                        status            varchar(255) NOT NULL,
                        is_seller         boolean      NOT NULL,
                        CONSTRAINT pk_member PRIMARY KEY (id),
                        CONSTRAINT uk_member_uuid UNIQUE (uuid),
                        CONSTRAINT uk_member_email UNIQUE (email),
                        CONSTRAINT uk_member_nickname UNIQUE (nickname),
                        CONSTRAINT ck_member_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'BANNED'))
);

-- address
CREATE TABLE address (
                         id               bigint GENERATED BY DEFAULT AS IDENTITY,
                         created_at       timestamp(6) NOT NULL,
                         updated_at       timestamp(6) NOT NULL,
                         member_id        bigint       NOT NULL,
                         alias            varchar(50),
                         recipient        varchar(50)  NOT NULL,
                         recipient_phone  varchar(255) NOT NULL,
                         zipcode          varchar(255) NOT NULL,
                         address          varchar(255) NOT NULL,
                         address_detail   varchar(255),
                         is_default       boolean      NOT NULL,
                         CONSTRAINT pk_address PRIMARY KEY (id)
);
CREATE INDEX idx_address_member_id ON address (member_id);

-- seller
CREATE TABLE seller (
                        id              bigint GENERATED BY DEFAULT AS IDENTITY,
                        created_at      timestamp(6) NOT NULL,
                        updated_at      timestamp(6) NOT NULL,
                        member_id       bigint       NOT NULL,
                        bank            varchar(255) NOT NULL,
                        account_number  varchar(255) NOT NULL,
                        account_holder  varchar(255) NOT NULL,
                        CONSTRAINT pk_seller PRIMARY KEY (id),
                        CONSTRAINT uk_seller_member_id UNIQUE (member_id)
);

-- refresh_token
CREATE TABLE refresh_token (
                               id             bigint GENERATED BY DEFAULT AS IDENTITY,
                               created_at     timestamp(6) NOT NULL,
                               updated_at     timestamp(6) NOT NULL,
                               member_id      bigint       NOT NULL,
                               refresh_token  varchar(500) NOT NULL,
                               expired_at     timestamp(6) NOT NULL,
                               revoked        boolean      NOT NULL,
                               CONSTRAINT pk_refresh_token PRIMARY KEY (id),
                               CONSTRAINT uk_refresh_token_token UNIQUE (refresh_token)
);
CREATE INDEX idx_refresh_token_member_id ON refresh_token (member_id);

-- member_warning
CREATE TABLE member_warning (
                                id              bigint GENERATED BY DEFAULT AS IDENTITY,
                                created_at      timestamp(6) NOT NULL,
                                updated_at      timestamp(6) NOT NULL,
                                member_id       bigint       NOT NULL,
                                source_context  varchar(30)  NOT NULL,
                                source_id       bigint       NOT NULL,
                                reason          varchar(30)  NOT NULL,
                                description     varchar(255),
                                occurred_at     timestamp(6) NOT NULL,
                                CONSTRAINT pk_member_warning PRIMARY KEY (id),
                                CONSTRAINT uk_member_warning_source UNIQUE (source_context, source_id)
);
CREATE INDEX idx_member_warning_member_id ON member_warning (member_id);

-- member_sanction
CREATE TABLE member_sanction (
                                 id              bigint GENERATED BY DEFAULT AS IDENTITY,
                                 created_at      timestamp(6) NOT NULL,
                                 updated_at      timestamp(6) NOT NULL,
                                 member_id       bigint       NOT NULL,
                                 sanction_type   varchar(20)  NOT NULL,
                                 reason          varchar(30)  NOT NULL,
                                 warning_count   integer      NOT NULL,
                                 started_at      timestamp(6) NOT NULL,
                                 expired_at      timestamp(6),
                                 released_at     timestamp(6),
                                 CONSTRAINT pk_member_sanction PRIMARY KEY (id),
                                 CONSTRAINT ck_member_sanction_type CHECK (sanction_type IN ('SUSPENDED', 'BANNED'))
);
CREATE INDEX idx_member_sanction_member_id ON member_sanction (member_id);