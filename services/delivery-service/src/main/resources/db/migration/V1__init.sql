CREATE TABLE delivery_member (
                                 id          bigint       NOT NULL,
                                 created_at  timestamp(6) NOT NULL,
                                 updated_at  timestamp(6) NOT NULL,
                                 uuid        uuid         NOT NULL,
                                 nickname    varchar(255) NOT NULL,
                                 CONSTRAINT pk_delivery_member PRIMARY KEY (id),
                                 CONSTRAINT uk_delivery_member_uuid UNIQUE (uuid)
);

CREATE TABLE delivery (
                          id          bigint GENERATED BY DEFAULT AS IDENTITY,
                          created_at  timestamp(6) NOT NULL,
                          updated_at  timestamp(6) NOT NULL,
                          order_id    bigint       NOT NULL,
                          winner_id   bigint       NOT NULL,
                          seller_id   bigint       NOT NULL,
                          carrier     varchar(255) NOT NULL,
                          waybill     varchar(255) NOT NULL,
                          status      varchar(255) NOT NULL,
                          CONSTRAINT pk_delivery PRIMARY KEY (id),
                          CONSTRAINT uk_delivery_order_id UNIQUE (order_id),
                          CONSTRAINT fk_delivery_winner FOREIGN KEY (winner_id) REFERENCES delivery_member (id),
                          CONSTRAINT fk_delivery_seller FOREIGN KEY (seller_id) REFERENCES delivery_member (id),
                          CONSTRAINT ck_delivery_carrier CHECK (carrier IN (
                              'CJ', 'LOTTE', 'EPOST', 'HANJIN', 'LOGEN', 'KDEXP', 'HDEXP', 'DAESIN', 'ILYANG',
                              'KUNYOUNG', 'CHUNIL', 'HONAM', 'COUPANG', 'CU_POST', 'GS_POSTBOX', 'HOMEPICK',
                              'GOODSTOLUCK', 'DELIBOX', 'YONGMA', 'TODAY_PICKUP', 'TODAY', 'LX_PANTOS', 'CWAY',
                              'SLX', 'LTL', 'HPL'
                          )),
                          CONSTRAINT ck_delivery_status CHECK (status IN (
                              'UNKNOWN', 'WAITING', 'INFORMATION_RECEIVED', 'AT_PICKUP', 'IN_TRANSIT',
                              'OUT_FOR_DELIVERY', 'ATTEMPT_FAIL', 'DELIVERED', 'AVAILABLE_FOR_PICKUP',
                              'EXCEPTION', 'WRONG'
                          ))
);
