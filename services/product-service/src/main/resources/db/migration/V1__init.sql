-- 상품·후기 서비스 초기 스키마
-- 빈 DB에서 ddl-auto: update로 Hibernate가 만든 DDL을 옮기고, 제약조건 이름만 읽기 쉽게 바꿨다.
-- 이미 적용된 이 파일은 수정하지 않는다. 스키마 변경은 V2__설명.sql로 추가한다.
-- enum 값을 추가하면 아래 CHECK 제약조건도 새 V 파일에서 함께 바꿔야 한다.

-- ── 상품 ──

-- 상품 서비스가 회원 이벤트로 복제해 둔 회원 (판매자·찜·문의 작성자)
CREATE TABLE product_member (
    id         bigint       NOT NULL,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    nickname   varchar(255) NOT NULL,
    CONSTRAINT pk_product_member PRIMARY KEY (id)
);

CREATE TABLE product (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at             timestamp(6) NOT NULL,
    updated_at             timestamp(6) NOT NULL,
    seller_id              bigint       NOT NULL,
    product_name           varchar(100) NOT NULL,
    category               varchar(255) NOT NULL,
    manufacturer           varchar(255) NOT NULL,
    manufacturer_etc       varchar(255),
    product_description    text         NOT NULL,
    shipping_fee_type      varchar(255) NOT NULL,
    shipping_fee           bigint       NOT NULL,
    bundle_shipping        boolean      NOT NULL,
    policy_version         varchar(255) NOT NULL,
    policy_agreed_at       timestamp(6) NOT NULL,
    -- 경매 조건
    start_price            bigint       NOT NULL,
    instant_win_price      bigint,
    duration               varchar(255) NOT NULL,
    custom_end_at          timestamp(6),
    -- 경매 진행 상태
    auction_scheduled_at   timestamp(6) NOT NULL,
    auction_requested_at   timestamp(6),
    current_auction_id     bigint,
    auction_status         varchar(255),
    auction_failure_reason varchar(255),
    auction_end_at         timestamp(6),
    round                  integer      NOT NULL,
    wish_count             integer      NOT NULL,
    deleted_at             timestamp(6),
    version                bigint       NOT NULL,
    CONSTRAINT pk_product PRIMARY KEY (id),
    CONSTRAINT fk_product_seller FOREIGN KEY (seller_id) REFERENCES product_member (id),
    CONSTRAINT ck_product_category CHECK (category IN ('CONSOLE', 'GAME_SOFTWARE', 'ACCESSORY', 'LIMITED_EDITION', 'ETC')),
    CONSTRAINT ck_product_manufacturer CHECK (manufacturer IN ('NINTENDO', 'SONY', 'MICROSOFT', 'SEGA', 'ETC')),
    CONSTRAINT ck_product_shipping_fee_type CHECK (shipping_fee_type IN ('FREE', 'FIXED_3000', 'FIXED_4000', 'CUSTOM')),
    CONSTRAINT ck_product_duration CHECK (duration IN ('DAYS_1', 'DAYS_3', 'DAYS_7', 'CUSTOM')),
    CONSTRAINT ck_product_auction_status CHECK (auction_status IN ('SCHEDULED', 'IN_PROGRESS', 'SOLD', 'FAILED')),
    CONSTRAINT ck_product_auction_failure_reason CHECK (auction_failure_reason IN ('NO_BID', 'UNPAID', 'REFUNDED'))
);

-- 상품 이미지 (업로드 직후엔 product_id가 비어 있고, 상품 등록 때 연결된다)
CREATE TABLE product_image (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at  timestamp(6) NOT NULL,
    updated_at  timestamp(6) NOT NULL,
    product_id  bigint,
    uploader_id bigint       NOT NULL,
    storage_key varchar(255) NOT NULL,
    format      varchar(255) NOT NULL,
    size        bigint       NOT NULL,
    sort_order  integer,
    CONSTRAINT pk_product_image PRIMARY KEY (id),
    CONSTRAINT uk_product_image_storage_key UNIQUE (storage_key),
    CONSTRAINT fk_product_image_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT fk_product_image_uploader FOREIGN KEY (uploader_id) REFERENCES product_member (id),
    CONSTRAINT ck_product_image_format CHECK (format IN ('JPEG', 'PNG', 'WEBP'))
);
CREATE INDEX idx_product_image_product_sort ON product_image (product_id, sort_order);

CREATE TABLE product_wish (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    member_id  bigint       NOT NULL,
    product_id bigint       NOT NULL,
    CONSTRAINT pk_product_wish PRIMARY KEY (id),
    CONSTRAINT uk_product_wish_member_product UNIQUE (member_id, product_id),
    CONSTRAINT fk_product_wish_member FOREIGN KEY (member_id) REFERENCES product_member (id),
    CONSTRAINT fk_product_wish_product FOREIGN KEY (product_id) REFERENCES product (id)
);

-- 상품 문의 (parent_id가 있으면 답변)
CREATE TABLE product_qna (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at          timestamp(6) NOT NULL,
    updated_at          timestamp(6) NOT NULL,
    product_id          bigint       NOT NULL,
    writer_id           bigint       NOT NULL,
    parent_id           bigint,
    product_qna_content text         NOT NULL,
    deleted_at          timestamp(6),
    CONSTRAINT pk_product_qna PRIMARY KEY (id),
    CONSTRAINT fk_product_qna_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT fk_product_qna_writer FOREIGN KEY (writer_id) REFERENCES product_member (id),
    CONSTRAINT fk_product_qna_parent FOREIGN KEY (parent_id) REFERENCES product_qna (id)
);

-- ── 후기 ──

-- 후기 쪽이 회원 이벤트로 복제해 둔 회원 (작성자·대상)
CREATE TABLE review_member (
    id         bigint       NOT NULL,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    nickname   varchar(255) NOT NULL,
    CONSTRAINT pk_review_member PRIMARY KEY (id)
);

-- 구매 확정 이벤트로 만들어지는 "후기를 쓸 수 있는 주문"
CREATE TABLE reviewable_order (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at      timestamp(6) NOT NULL,
    updated_at      timestamp(6) NOT NULL,
    order_id        bigint       NOT NULL,
    product_id      bigint       NOT NULL,
    product_name    varchar(255) NOT NULL,
    buyer_id        bigint       NOT NULL,
    seller_id       bigint       NOT NULL,
    winning_price   bigint       NOT NULL,
    confirmed_at    timestamp(6) NOT NULL,
    review_deadline timestamp(6) NOT NULL,
    reviewed        boolean      NOT NULL,
    CONSTRAINT pk_reviewable_order PRIMARY KEY (id),
    CONSTRAINT uk_reviewable_order_order UNIQUE (order_id),
    CONSTRAINT fk_reviewable_order_buyer FOREIGN KEY (buyer_id) REFERENCES review_member (id),
    CONSTRAINT fk_reviewable_order_seller FOREIGN KEY (seller_id) REFERENCES review_member (id)
);

CREATE TABLE review (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at          timestamp(6) NOT NULL,
    updated_at          timestamp(6) NOT NULL,
    reviewable_order_id bigint       NOT NULL,
    writer_id           bigint       NOT NULL,
    target_id           bigint       NOT NULL,
    rating              numeric(2, 1) NOT NULL,
    review_content      text         NOT NULL,
    deleted_at          timestamp(6),
    CONSTRAINT pk_review PRIMARY KEY (id),
    CONSTRAINT uk_review_reviewable_order UNIQUE (reviewable_order_id),
    CONSTRAINT fk_review_reviewable_order FOREIGN KEY (reviewable_order_id) REFERENCES reviewable_order (id),
    CONSTRAINT fk_review_writer FOREIGN KEY (writer_id) REFERENCES review_member (id),
    CONSTRAINT fk_review_target FOREIGN KEY (target_id) REFERENCES review_member (id)
);
