CREATE TABLE notification_device (
                                     id         bigint GENERATED BY DEFAULT AS IDENTITY,
                                     created_at timestamp(6) NOT NULL,
                                     updated_at timestamp(6) NOT NULL,
                                     member_id  bigint       NOT NULL,
                                     token      varchar(512) NOT NULL,
                                     platform   varchar(20)  NOT NULL,
                                     CONSTRAINT pk_notification_device PRIMARY KEY (id),
                                     CONSTRAINT uk_notification_device_token UNIQUE (token),
                                     CONSTRAINT ck_notification_device_platform CHECK (platform IN ('WEB'))
);

CREATE INDEX idx_notification_device_member ON notification_device (member_id);

CREATE TABLE notification_setting (
                                      id           bigint GENERATED BY DEFAULT AS IDENTITY,
                                      created_at   timestamp(6) NOT NULL,
                                      updated_at   timestamp(6) NOT NULL,
                                      member_id    bigint      NOT NULL,
                                      category     varchar(20) NOT NULL,
                                      push_enabled boolean     NOT NULL,
                                      CONSTRAINT pk_notification_setting PRIMARY KEY (id),
                                      CONSTRAINT uk_notification_setting_member_category UNIQUE (member_id, category),
                                      CONSTRAINT ck_notification_setting_category CHECK (category IN ('BID', 'BUY', 'SELL', 'INTEREST'))
);