CREATE TABLE notification (
                              id                bigint GENERATED BY DEFAULT AS IDENTITY,
                              created_at        timestamp(6) NOT NULL,
                              updated_at        timestamp(6) NOT NULL,
                              receiver_id       bigint       NOT NULL,
                              type              varchar(50)  NOT NULL,
                              category          varchar(20)  NOT NULL,
                              title             varchar(100) NOT NULL,
                              body              varchar(500) NOT NULL,
                              target_type       varchar(20)  NOT NULL,
                              target_id         bigint       NOT NULL,
                              dedupe_key        varchar(150) NOT NULL,
                              event_occurred_at timestamp(6),
                              pushed_at         timestamp(6),
                              read_at           timestamp(6),
                              CONSTRAINT pk_notification PRIMARY KEY (id),
                              CONSTRAINT uk_notification_dedupe UNIQUE (dedupe_key),
                              CONSTRAINT ck_notification_category CHECK (category IN ('BID', 'BUY', 'SELL', 'INTEREST', 'ACCOUNT')),
                              CONSTRAINT ck_notification_target_type CHECK (target_type IN ('AUCTION', 'ORDER', 'PRODUCT', 'CART', 'SETTLEMENT', 'MEMBER'))
);

CREATE INDEX idx_notification_receiver ON notification (receiver_id, id DESC);
CREATE INDEX idx_notification_receiver_category ON notification (receiver_id, category, id DESC);
CREATE INDEX idx_notification_unread ON notification (receiver_id) WHERE read_at IS NULL;