-- settlement_product (product.registered 복사본, PK = 상품 id)
CREATE TABLE settlement_product (
                                    id          bigint       NOT NULL,
                                    created_at  timestamp(6) NOT NULL,
                                    updated_at  timestamp(6) NOT NULL,
                                    name        varchar(100) NOT NULL,
                                    CONSTRAINT pk_settlement_product PRIMARY KEY (id)
);

-- settlement
CREATE TABLE settlement (
                            id                 bigint GENERATED BY DEFAULT AS IDENTITY,
                            created_at         timestamp(6) NOT NULL,
                            updated_at         timestamp(6) NOT NULL,
                            order_id           bigint       NOT NULL,
                            seller_id          bigint       NOT NULL,
                            product_id         bigint       NOT NULL,
                            product_name       varchar(255) NOT NULL,
                            winning_price      bigint       NOT NULL,
                            delivery_fee       bigint       NOT NULL,
                            fee_amount         bigint       NOT NULL,
                            settlement_amount  bigint       NOT NULL,
                            status             varchar(20)  NOT NULL,
                            confirmed_at       timestamp(6) NOT NULL,
                            payout_date        date         NOT NULL,
                            completed_at       timestamp(6),
                            version            bigint,
                            CONSTRAINT pk_settlement PRIMARY KEY (id),
                            CONSTRAINT uk_settlement_order_id UNIQUE (order_id),
                            CONSTRAINT ck_settlement_status CHECK (status IN ('PENDING', 'COMPLETED'))
);
CREATE INDEX idx_settlement_seller_status ON settlement (seller_id, status);
CREATE INDEX idx_settlement_status_payout_date ON settlement (status, payout_date);