CREATE TABLE pending_interaction (
                                     id           bigint GENERATED BY DEFAULT AS IDENTITY,
                                     created_at   timestamp(6) NOT NULL,
                                     updated_at   timestamp(6) NOT NULL,
                                     member_id    bigint       NOT NULL,
                                     product_id   bigint       NOT NULL,
                                     change_type  varchar(255) NOT NULL,
                                     occurred_at  timestamp(6) NOT NULL,
                                     CONSTRAINT pk_pending_interaction PRIMARY KEY (id),
                                     CONSTRAINT ck_pending_interaction_change_type CHECK (change_type IN ('WISHED', 'UNWISHED'))
);
CREATE INDEX idx_pending_interaction_product_id ON pending_interaction (product_id);