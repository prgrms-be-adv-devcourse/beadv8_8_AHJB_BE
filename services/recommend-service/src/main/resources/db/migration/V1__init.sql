CREATE TABLE recommend_member (
                                  id          bigint       NOT NULL,
                                  created_at  timestamp(6) NOT NULL,
                                  updated_at  timestamp(6) NOT NULL,
                                  uuid        uuid         NOT NULL,
                                  nickname    varchar(255) NOT NULL,
                                  CONSTRAINT pk_recommend_member PRIMARY KEY (id),
                                  CONSTRAINT uk_recommend_member_uuid UNIQUE (uuid)
);

CREATE TABLE recommend_product (
                                   id             bigint       NOT NULL,
                                   created_at     timestamp(6) NOT NULL,
                                   updated_at     timestamp(6) NOT NULL,
                                   version        bigint       NOT NULL,
                                   seller_id      bigint       NOT NULL,
                                   product_name   varchar(255) NOT NULL,
                                   category       varchar(255) NOT NULL,
                                   manufacturer   varchar(255) NOT NULL,
                                   thumbnail_url  varchar(255),
                                   deleted        boolean      NOT NULL,
                                   CONSTRAINT pk_recommend_product PRIMARY KEY (id)
);

CREATE TABLE recommend_auction (
                                   id                 bigint       NOT NULL,
                                   created_at         timestamp(6) NOT NULL,
                                   updated_at         timestamp(6) NOT NULL,
                                   product_id         bigint       NOT NULL,
                                   instant_win_price  bigint,
                                   current_price      bigint,
                                   bid_count          bigint       NOT NULL,
                                   start_at           timestamp(6) NOT NULL,
                                   end_at             timestamp(6) NOT NULL,
                                   ended_at           timestamp(6),
                                   status             varchar(255) NOT NULL,
                                   CONSTRAINT pk_recommend_auction PRIMARY KEY (id),
                                   CONSTRAINT ck_recommend_auction_status CHECK (status IN ('ACTIVE', 'ENDED'))
);
CREATE INDEX idx_auction_status_end_at ON recommend_auction (status, end_at);

CREATE TABLE interaction (
                             id                bigint GENERATED BY DEFAULT AS IDENTITY,
                             created_at        timestamp(6) NOT NULL,
                             updated_at        timestamp(6) NOT NULL,
                             member_id         bigint       NOT NULL,
                             auction_id        bigint       NOT NULL,
                             product_id        bigint       NOT NULL,
                             type              varchar(255) NOT NULL,
                             active            boolean,
                             last_occurred_at  timestamp(6),
                             CONSTRAINT pk_interaction PRIMARY KEY (id),
                             CONSTRAINT uk_interaction_member_auction_type UNIQUE (member_id, auction_id, type),
                             CONSTRAINT fk_interaction_member FOREIGN KEY (member_id) REFERENCES recommend_member (id),
                             CONSTRAINT fk_interaction_auction FOREIGN KEY (auction_id) REFERENCES recommend_auction (id),
                             CONSTRAINT fk_interaction_product FOREIGN KEY (product_id) REFERENCES recommend_product (id),
                             CONSTRAINT ck_interaction_type CHECK (type IN ('WIN', 'BID', 'WISH'))
);

CREATE TABLE interaction_log (
                                 id                bigint GENERATED BY DEFAULT AS IDENTITY,
                                 created_at        timestamp(6) NOT NULL,
                                 updated_at        timestamp(6) NOT NULL,
                                 member_id         bigint       NOT NULL,
                                 auction_id        bigint       NOT NULL,
                                 product_id        bigint       NOT NULL,
                                 type              varchar(255) NOT NULL,
                                 last_occurred_at  timestamp(6) NOT NULL,
                                 CONSTRAINT pk_interaction_log PRIMARY KEY (id),
                                 CONSTRAINT uk_interaction_log_member_auction_type_occurred UNIQUE (member_id, auction_id, type, last_occurred_at),
                                 CONSTRAINT fk_interaction_log_member FOREIGN KEY (member_id) REFERENCES recommend_member (id),
                                 CONSTRAINT fk_interaction_log_auction FOREIGN KEY (auction_id) REFERENCES recommend_auction (id),
                                 CONSTRAINT fk_interaction_log_product FOREIGN KEY (product_id) REFERENCES recommend_product (id),
                                 CONSTRAINT ck_interaction_log_type CHECK (type IN ('WIN', 'BID', 'WISH'))
);
