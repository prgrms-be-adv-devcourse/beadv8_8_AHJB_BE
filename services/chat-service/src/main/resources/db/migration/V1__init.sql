-- chat_member (member.created 복사본, PK = 회원 id)
CREATE TABLE chat_member (
                             id          bigint       NOT NULL,
                             created_at  timestamp(6) NOT NULL,
                             updated_at  timestamp(6) NOT NULL,
                             uuid        uuid         NOT NULL,
                             nickname    varchar(50)  NOT NULL,
                             CONSTRAINT pk_chat_member PRIMARY KEY (id),
                             CONSTRAINT uk_chat_member_uuid UNIQUE (uuid)
);

-- chat_product (product.registered 복사본, PK = 상품 id)
CREATE TABLE chat_product (
                              id             bigint       NOT NULL,
                              created_at     timestamp(6) NOT NULL,
                              updated_at     timestamp(6) NOT NULL,
                              name           varchar(100) NOT NULL,
                              thumbnail_url  varchar(255),
                              CONSTRAINT pk_chat_product PRIMARY KEY (id)
);

-- chat_room (낙찰 1건 = 방 1개)
CREATE TABLE chat_room (
                           id                     bigint GENERATED BY DEFAULT AS IDENTITY,
                           created_at             timestamp(6) NOT NULL,
                           updated_at             timestamp(6) NOT NULL,
                           auction_id             bigint       NOT NULL,
                           product_id             bigint       NOT NULL,
                           product_name           varchar(100) NOT NULL,
                           product_thumbnail_url  varchar(255),
                           winner_id              bigint       NOT NULL,
                           seller_id              bigint       NOT NULL,
                           status                 varchar(20)  NOT NULL,
                           last_message_at        timestamp(6),
                           CONSTRAINT pk_chat_room PRIMARY KEY (id),
                           CONSTRAINT uk_chat_room_auction_id UNIQUE (auction_id),
                           CONSTRAINT ck_chat_room_status CHECK (status IN ('OPEN', 'CLOSED'))
);
CREATE INDEX idx_chat_room_winner_last_message ON chat_room (winner_id, last_message_at);
CREATE INDEX idx_chat_room_seller_last_message ON chat_room (seller_id, last_message_at);

-- chat_message (INSERT만)
CREATE TABLE chat_message (
                              id          bigint GENERATED BY DEFAULT AS IDENTITY,
                              created_at  timestamp(6) NOT NULL,
                              updated_at  timestamp(6) NOT NULL,
                              room_id     bigint        NOT NULL,
                              sender_id   bigint        NOT NULL,
                              content     varchar(1000) NOT NULL,
                              CONSTRAINT pk_chat_message PRIMARY KEY (id)
);
CREATE INDEX idx_chat_message_room_id ON chat_message (room_id, id);