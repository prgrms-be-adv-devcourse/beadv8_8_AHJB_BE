-- wallet_member
CREATE TABLE wallet_member (
                               id          bigint       NOT NULL,
                               created_at  timestamp(6) NOT NULL,
                               updated_at  timestamp(6) NOT NULL,
                               uuid        uuid         NOT NULL,
                               CONSTRAINT pk_wallet_member PRIMARY KEY (id),
                               CONSTRAINT uk_wallet_member_uuid UNIQUE (uuid)
);

-- wallet
CREATE TABLE wallet (
                        id                  bigint GENERATED BY DEFAULT AS IDENTITY,
                        created_at          timestamp(6) NOT NULL,
                        updated_at          timestamp(6) NOT NULL,
                        balance             bigint       NOT NULL,
                        settlement_balance  bigint       NOT NULL,
                        type                varchar(20)  NOT NULL,
                        version             bigint       NOT NULL,
                        holder_id           bigint,
                        CONSTRAINT pk_wallet PRIMARY KEY (id),
                        CONSTRAINT fk_wallet_holder FOREIGN KEY (holder_id) REFERENCES wallet_member (id),
                        CONSTRAINT ck_wallet_type CHECK (type IN ('USER', 'ESCROW', 'FEE'))
);

-- payment
CREATE TABLE payment (
                         id               bigint GENERATED BY DEFAULT AS IDENTITY,
                         created_at       timestamp(6) NOT NULL,
                         updated_at       timestamp(6) NOT NULL,
                         charge_amount    bigint       NOT NULL,
                         failed_at        timestamp(6),
                         failure_reason   varchar(200),
                         holder_id        bigint       NOT NULL,
                         idempotency_key  varchar(100) NOT NULL,
                         order_group_id   bigint       NOT NULL,
                         paid_at          timestamp(6),
                         status           varchar(20)  NOT NULL,
                         total_price      bigint       NOT NULL,
                         buyer_wallet_id  bigint       NOT NULL,
                         CONSTRAINT pk_payment PRIMARY KEY (id),
                         CONSTRAINT uk_payment_order_group UNIQUE (order_group_id),
                         CONSTRAINT uk_payment_idempotency UNIQUE (idempotency_key),
                         CONSTRAINT fk_payment_buyer_wallet FOREIGN KEY (buyer_wallet_id) REFERENCES wallet (id),
                         CONSTRAINT ck_payment_status CHECK (status IN ('PENDING', 'CHARGING', 'PAID', 'FAILED'))
);
CREATE INDEX idx_payment_holder ON payment (holder_id, created_at);

-- payment_item
CREATE TABLE payment_item (
                              id             bigint GENERATED BY DEFAULT AS IDENTITY,
                              created_at     timestamp(6) NOT NULL,
                              updated_at     timestamp(6) NOT NULL,
                              delivery_fee   bigint       NOT NULL,
                              order_id       bigint       NOT NULL,
                              refunded_at    timestamp(6),
                              seller_id      bigint       NOT NULL,
                              winning_price  bigint       NOT NULL,
                              payment_id     bigint       NOT NULL,
                              CONSTRAINT pk_payment_item PRIMARY KEY (id),
                              CONSTRAINT uk_payment_item_order UNIQUE (order_id),
                              CONSTRAINT fk_payment_item_payment FOREIGN KEY (payment_id) REFERENCES payment (id)
);

-- charge
CREATE TABLE charge (
                        id                bigint GENERATED BY DEFAULT AS IDENTITY,
                        created_at        timestamp(6) NOT NULL,
                        updated_at        timestamp(6) NOT NULL,
                        aborted_at        timestamp(6),
                        amount            bigint       NOT NULL,
                        approved_at       timestamp(6),
                        canceled_at       timestamp(6),
                        charged_at        timestamp(6),
                        failure_code      varchar(50),
                        failure_message   varchar(510),
                        holder_id         bigint       NOT NULL,
                        method            varchar(30),
                        payment_key       varchar(200),
                        pg_order_id       varchar(64)  NOT NULL,
                        purpose           varchar(20)  NOT NULL,
                        receipt_url       varchar(500),
                        remaining_amount  bigint       NOT NULL,
                        status            varchar(20)  NOT NULL,
                        used_at           timestamp(6),
                        version           bigint       NOT NULL DEFAULT 0,
                        payment_id        bigint,
                        wallet_id         bigint       NOT NULL,
                        CONSTRAINT pk_charge PRIMARY KEY (id),
                        CONSTRAINT uk_charge_pg_order UNIQUE (pg_order_id),
                        CONSTRAINT uk_charge_payment_key UNIQUE (payment_key),
                        CONSTRAINT fk_charge_payment FOREIGN KEY (payment_id) REFERENCES payment (id),
                        CONSTRAINT fk_charge_wallet FOREIGN KEY (wallet_id) REFERENCES wallet (id),
                        CONSTRAINT ck_charge_purpose CHECK (purpose IN ('MANUAL', 'FOR_PAYMENT')),
                        CONSTRAINT ck_charge_status CHECK (status IN ('REQUESTED', 'CHARGED', 'USED', 'CANCELED', 'ABORTED'))
);
CREATE INDEX idx_charge_wallet ON charge (wallet_id, created_at);
CREATE INDEX idx_charge_status ON charge (status, created_at);

-- holding
CREATE TABLE holding (
                         id                bigint GENERATED BY DEFAULT AS IDENTITY,
                         created_at        timestamp(6) NOT NULL,
                         updated_at        timestamp(6) NOT NULL,
                         amount            bigint       NOT NULL,
                         confirmed_at      timestamp(6),
                         delivery_fee      bigint       NOT NULL,
                         fee_amount        bigint       NOT NULL,
                         order_id          bigint       NOT NULL,
                         payment_id        bigint       NOT NULL,
                         refunded_at       timestamp(6),
                         released_at       timestamp(6),
                         status            varchar(20)  NOT NULL,
                         winning_price     bigint       NOT NULL,
                         buyer_wallet_id   bigint       NOT NULL,
                         seller_wallet_id  bigint       NOT NULL,
                         CONSTRAINT pk_holding PRIMARY KEY (id),
                         CONSTRAINT uk_holding_order UNIQUE (order_id),
                         CONSTRAINT fk_holding_buyer_wallet FOREIGN KEY (buyer_wallet_id) REFERENCES wallet (id),
                         CONSTRAINT fk_holding_seller_wallet FOREIGN KEY (seller_wallet_id) REFERENCES wallet (id),
                         CONSTRAINT ck_holding_status CHECK (status IN ('HELD', 'CONFIRMED', 'RELEASED', 'REFUNDED'))
);

-- wallet_transactions
CREATE TABLE wallet_transactions (
                                     id                    bigint GENERATED BY DEFAULT AS IDENTITY,
                                     account               varchar(20)  NOT NULL,
                                     amount                bigint       NOT NULL,
                                     balance_after         bigint       NOT NULL,
                                     created_at            timestamp(6) NOT NULL,
                                     idempotency_key       varchar(100) NOT NULL,
                                     reference_id          bigint       NOT NULL,
                                     reference_type        varchar(20)  NOT NULL,
                                     transaction_group_id  varchar(36)  NOT NULL,
                                     type                  varchar(30)  NOT NULL,
                                     wallet_id             bigint       NOT NULL,
                                     CONSTRAINT pk_wallet_transactions PRIMARY KEY (id),
                                     CONSTRAINT uk_wallet_tx_idempotency UNIQUE (idempotency_key),
                                     CONSTRAINT fk_wallet_tx_wallet FOREIGN KEY (wallet_id) REFERENCES wallet (id),
                                     CONSTRAINT ck_wallet_tx_account CHECK (account IN ('DEPOSIT', 'SETTLEMENT')),
                                     CONSTRAINT ck_wallet_tx_reference_type CHECK (reference_type IN ('PAYMENT', 'ORDER', 'WITHDRAWAL')),
                                     CONSTRAINT ck_wallet_tx_type CHECK (type IN ('CHARGE', 'CHARGE_CANCEL', 'WITHDRAWAL',
                                                                                  'HOLD_PAY', 'HOLD_RECEIVE',
                                                                                  'SETTLEMENT_PAY', 'SETTLEMENT_RECEIVE',
                                                                                  'FEE_PAY', 'FEE_RECEIVE',
                                                                                  'REFUND_PAY', 'REFUND_RECEIVE',
                                                                                  'REVERSAL'))
);
CREATE INDEX idx_wallet_tx_wallet ON wallet_transactions (wallet_id, created_at);
CREATE INDEX idx_wallet_tx_wallet_account ON wallet_transactions (wallet_id, account);
CREATE INDEX idx_wallet_tx_group ON wallet_transactions (transaction_group_id);
CREATE INDEX idx_wallet_tx_reference ON wallet_transactions (reference_type, reference_id);

-- withdrawal
CREATE TABLE withdrawal (
                            id              bigint GENERATED BY DEFAULT AS IDENTITY,
                            created_at      timestamp(6) NOT NULL,
                            updated_at      timestamp(6) NOT NULL,
                            account         varchar(20)  NOT NULL,
                            amount          bigint       NOT NULL,
                            completed_at    timestamp(6),
                            failed_at       timestamp(6),
                            failure_reason  varchar(255),
                            holder_id       bigint       NOT NULL,
                            status          varchar(20)  NOT NULL,
                            wallet_id       bigint       NOT NULL,
                            CONSTRAINT pk_withdrawal PRIMARY KEY (id),
                            CONSTRAINT fk_withdrawal_wallet FOREIGN KEY (wallet_id) REFERENCES wallet (id),
                            CONSTRAINT ck_withdrawal_account CHECK (account IN ('DEPOSIT', 'SETTLEMENT')),
                            CONSTRAINT ck_withdrawal_status CHECK (status IN ('REQUESTED', 'COMPLETED', 'FAILED'))
);
CREATE INDEX idx_withdrawal_holder ON withdrawal (holder_id, created_at);

-- toss_webhook_event
CREATE TABLE toss_webhook_event (
                                    id            bigint GENERATED BY DEFAULT AS IDENTITY,
                                    created_at    timestamp(6) NOT NULL,
                                    updated_at    timestamp(6) NOT NULL,
                                    event_type    varchar(50)  NOT NULL,
                                    last_error    varchar(500),
                                    order_id      varchar(64),
                                    payment_key   varchar(200),
                                    processed_at  timestamp(6),
                                    raw_body      text         NOT NULL,
                                    retry_count   integer      NOT NULL,
                                    status        varchar(20)  NOT NULL,
                                    CONSTRAINT pk_toss_webhook_event PRIMARY KEY (id),
                                    CONSTRAINT ck_toss_webhook_event_status CHECK (status IN ('RECEIVED', 'PROCESSED', 'IGNORED', 'FAILED'))
);
CREATE INDEX idx_toss_webhook_status ON toss_webhook_event (status, created_at);
CREATE INDEX idx_toss_webhook_order ON toss_webhook_event (order_id);
