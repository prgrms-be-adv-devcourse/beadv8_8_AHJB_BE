-- reconciliation_run
CREATE TABLE reconciliation_run (
                                    id              bigint GENERATED BY DEFAULT AS IDENTITY,
                                    created_at      timestamp(6) NOT NULL,
                                    updated_at      timestamp(6) NOT NULL,
                                    attempt         integer      NOT NULL,
                                    checked_count   integer      NOT NULL,
                                    failure_reason  varchar(500),
                                    finished_at     timestamp(6),
                                    mismatch_count  integer      NOT NULL,
                                    started_at      timestamp(6) NOT NULL,
                                    status          varchar(20)  NOT NULL,
                                    target_date     date         NOT NULL,
                                    type            varchar(20)  NOT NULL,
                                    CONSTRAINT pk_reconciliation_run PRIMARY KEY (id),
                                    CONSTRAINT uk_reconciliation_run_type_date UNIQUE (type, target_date),
                                    CONSTRAINT ck_reconciliation_run_status CHECK (status IN ('RUNNING', 'MATCHED', 'MISMATCHED', 'FAILED')),
                                    CONSTRAINT ck_reconciliation_run_type CHECK (type IN ('PG', 'LEDGER'))
);
CREATE INDEX idx_reconciliation_run_status ON reconciliation_run (status, target_date);

-- reconciliation_mismatch
CREATE TABLE reconciliation_mismatch (
                                         id               bigint GENERATED BY DEFAULT AS IDENTITY,
                                         created_at       timestamp(6) NOT NULL,
                                         updated_at       timestamp(6) NOT NULL,
                                         actual_amount    bigint,
                                         actual_state     varchar(30),
                                         detail           varchar(500),
                                         expected_amount  bigint,
                                         expected_state   varchar(30),
                                         pg_order_id      varchar(64),
                                         resolution_note  varchar(500),
                                         resolved_at      timestamp(6),
                                         resolved_by      varchar(50),
                                         status           varchar(20)  NOT NULL,
                                         target_key       varchar(64)  NOT NULL,
                                         target_type      varchar(20)  NOT NULL,
                                         type             varchar(40)  NOT NULL,
                                         run_id           bigint       NOT NULL,
                                         CONSTRAINT pk_reconciliation_mismatch PRIMARY KEY (id),
                                         CONSTRAINT uk_reconciliation_mismatch_target UNIQUE (run_id, type, target_type, target_key),
                                         CONSTRAINT fk_reconciliation_mismatch_run FOREIGN KEY (run_id) REFERENCES reconciliation_run (id),
                                         CONSTRAINT ck_reconciliation_mismatch_status CHECK (status IN ('OPEN', 'RESOLVED', 'IGNORED')),
                                         CONSTRAINT ck_reconciliation_mismatch_target_type CHECK (target_type IN ('CHARGE', 'PG_TRANSACTION', 'WALLET', 'HOLDING', 'LEDGER_GROUP')),
                                         CONSTRAINT ck_reconciliation_mismatch_type CHECK (type IN ('PG_ONLY', 'INTERNAL_ONLY', 'PG_APPROVED_NOT_REFLECTED',
                                                                                                    'PG_CANCELED_NOT_REFLECTED', 'INTERNAL_CANCELED_NOT_IN_PG', 'AMOUNT_MISMATCH',
                                                                                                    'LEDGER_GROUP_UNBALANCED', 'BALANCE_LEDGER_MISMATCH', 'ESCROW_HOLDING_MISMATCH',
                                                                                                    'DEPOSIT_REMAINING_MISMATCH', 'CHARGE_LEDGER_MISMATCH', 'HOLDING_LEDGER_MISMATCH'))
);
CREATE INDEX idx_reconciliation_mismatch_status ON reconciliation_mismatch (status, created_at);
CREATE INDEX idx_reconciliation_mismatch_pg_order ON reconciliation_mismatch (pg_order_id);
