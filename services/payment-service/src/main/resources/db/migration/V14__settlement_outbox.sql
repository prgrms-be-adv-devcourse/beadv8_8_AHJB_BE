-- 정산 아웃박스
-- 정산 지급 요청 이벤트를 정산 변경과 같은 트랜잭션에서 저장하고, 스케줄러가 Kafka 로 보낸다
-- published_at: Kafka 전송이 끝난 시각. 아직 보내지 않은 행은 NULL
CREATE TABLE settlement_outbox (
                                   id            bigint GENERATED BY DEFAULT AS IDENTITY,
                                   created_at    timestamp(6) NOT NULL,
                                   updated_at    timestamp(6) NOT NULL,
                                   topic         varchar(100) NOT NULL,
                                   message_key   varchar(100) NOT NULL,
                                   payload       text         NOT NULL,
                                   published_at  timestamp(6),
                                   CONSTRAINT pk_settlement_outbox PRIMARY KEY (id)
);

CREATE INDEX idx_settlement_outbox_published_at ON settlement_outbox (published_at, id);